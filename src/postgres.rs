//! Durable PostgreSQL job queue and transactional outbox (feature `postgres`, ADR 0036).
//!
//! [`PgQueue`] is a [`Transport`] over a SQLx [`PgPool`] from
//! `rustclamp-postgres`. Jobs are rows in `worker_jobs`, created by the
//! [`migration`] the application adds to its own `Migrations` plan. [`enqueue`]
//! inserts one on the caller's connection or open transaction, so a business
//! write and the job it triggers commit together (the outbox).
//!
//! Unlike [`SqliteQueue`](crate::sqlite::SqliteQueue), several consumers may
//! share one database: `claim` uses `FOR UPDATE SKIP LOCKED`, and every claim
//! is a lease. A row whose lease ran out (its consumer crashed, or held it
//! longer than the visibility timeout) is claimable again, so there is no
//! global `recover`.

use std::io;
use std::sync::Arc;
use std::time::{Duration, SystemTime};

use rustclamp_core::Clock;
use rustclamp_messaging::MessageEnvelope;
use rustclamp_postgres::Migration;
use rustclamp_postgres::sqlx::{self, PgConnection, PgPool};

use crate::service::{Claim, Settlement, Transport, unix_ms};

const SCHEMA: &str = "
CREATE TABLE worker_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id TEXT NOT NULL,
    message TEXT NOT NULL,
    dedupe_key TEXT UNIQUE,
    run_at BIGINT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending',
    attempts BIGINT NOT NULL DEFAULT 0,
    claims BIGINT NOT NULL DEFAULT 0,
    claimed_until BIGINT,
    result TEXT,
    reason TEXT,
    error TEXT
);
CREATE INDEX worker_jobs_due ON worker_jobs (state, run_at);";

/// The migration that creates `worker_jobs`, as `version` in the
/// application's `rustclamp_postgres::Migrations` plan. Pools never migrate on
/// connect, so the application runs it like its own migrations.
pub fn migration(version: i64) -> Migration {
    Migration {
        version,
        description: "rustclamp-worker: worker_jobs",
        sql: SCHEMA,
    }
}

/// Adds a pending job that becomes claimable at `run_at`.
///
/// Pass the application's open transaction (`&mut tx` derefs to
/// `&mut PgConnection`) to make the job commit or roll back with the rest of
/// it. A job whose `dedupe_key` already exists is not added; returns whether a
/// row was inserted.
pub async fn enqueue(
    conn: &mut PgConnection,
    message: &MessageEnvelope,
    run_at: SystemTime,
    dedupe_key: Option<&str>,
) -> Result<bool, sqlx::Error> {
    let json = serde_json::to_string(message).map_err(|error| sqlx::Error::Encode(error.into()))?;
    let inserted = sqlx::query(
        "INSERT INTO worker_jobs (message_id, message, dedupe_key, run_at)
         VALUES ($1, $2, $3, $4) ON CONFLICT (dedupe_key) DO NOTHING",
    )
    .bind(&message.id)
    .bind(json)
    .bind(dedupe_key)
    .bind(unix_ms(run_at))
    .execute(conn)
    .await?;
    Ok(inserted.rows_affected() == 1)
}

/// A [`Transport`] over the `worker_jobs` table, safe for many consumers.
///
/// Each claim holds the row for `visibility`; after that another consumer may
/// claim it again. `visibility` must cover the longest time the service holds a
/// claim: waiting for a runner, every attempt and every backoff in between.
pub struct PgQueue {
    pool: PgPool,
    clock: Arc<dyn Clock>,
    visibility: Duration,
}

impl PgQueue {
    /// Claims from `pool`; due-ness and leases are read from `clock`.
    pub fn new(pool: PgPool, clock: Arc<dyn Clock>, visibility: Duration) -> Self {
        Self {
            pool,
            clock,
            visibility,
        }
    }
}

impl Transport for PgQueue {
    /// The row id and its claim count, which identifies this lease.
    type Receipt = (i64, i64);

    async fn claim(&mut self, limit: usize) -> io::Result<Vec<Claim<(i64, i64)>>> {
        let now = self.clock.now();
        let until = unix_ms(now + self.visibility);
        let now = unix_ms(now);
        let mut rows: Vec<(i64, i64, i64, String, String)> = sqlx::query_as(
            "WITH due AS (
                 SELECT id FROM worker_jobs
                 WHERE (state = 'pending' AND run_at <= $1)
                    OR (state = 'claimed' AND claimed_until <= $1)
                 ORDER BY run_at, id LIMIT $2
                 FOR UPDATE SKIP LOCKED)
             UPDATE worker_jobs SET state = 'claimed', claims = claims + 1, claimed_until = $3
             FROM due WHERE worker_jobs.id = due.id
             RETURNING worker_jobs.id, claims, run_at, message_id, message",
        )
        .bind(now)
        .bind(i64::try_from(limit).unwrap_or(i64::MAX))
        .bind(until)
        .fetch_all(&self.pool)
        .await
        .map_err(io::Error::other)?;
        // RETURNING does not promise an order.
        rows.sort_by_key(|(id, _, run_at, ..)| (*run_at, *id));
        Ok(rows
            .into_iter()
            .map(|(row, claim, _, id, json)| {
                let receipt = (row, claim);
                match serde_json::from_str(&json) {
                    Ok(message) => Claim::Message { receipt, message },
                    Err(error) => Claim::Malformed {
                        receipt,
                        id,
                        error: error.to_string(),
                    },
                }
            })
            .collect())
    }

    async fn settle(&mut self, (id, claim): (i64, i64), settlement: Settlement) -> io::Result<()> {
        // Only while this claim still owns the row: a consumer whose lease ran
        // out must not overwrite the new owner's outcome.
        let query = match settlement {
            Settlement::Done {
                result, attempts, ..
            } => sqlx::query(
                "UPDATE worker_jobs SET state = 'done', attempts = $3, result = $4
                 WHERE id = $1 AND claims = $2 AND state = 'claimed'",
            )
            .bind(id)
            .bind(claim)
            .bind(i64::from(attempts))
            .bind(result.to_string()),
            Settlement::DeadLetter {
                reason,
                attempts,
                error,
                ..
            } => sqlx::query(
                "UPDATE worker_jobs SET state = 'dead', attempts = $3, reason = $4, error = $5
                 WHERE id = $1 AND claims = $2 AND state = 'claimed'",
            )
            .bind(id)
            .bind(claim)
            .bind(i64::from(attempts))
            .bind(format!("{reason:?}"))
            .bind(error),
            Settlement::Release => sqlx::query(
                "UPDATE worker_jobs SET state = 'pending', claimed_until = NULL
                 WHERE id = $1 AND claims = $2 AND state = 'claimed'",
            )
            .bind(id)
            .bind(claim),
        };
        query.execute(&self.pool).await.map_err(io::Error::other)?;
        Ok(())
    }
}
